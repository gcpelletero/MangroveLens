/*
 * Retrieve the precomputed result for a selected period.
 *
 * Example:
 * getPrecomputedPersistentNdviStats(2019, 2023)
 */

function getPrecomputedPersistentNdviStats(startYear, endYear) {
  const start = Number(startYear);
  const end = Number(endYear);

  // Validate observation years.
  if (
    !Number.isInteger(start) ||
    !Number.isInteger(end) ||
    start < 2019 ||
    end > 2025 ||
    start > end
  ) {
    return null;
  }

  const result = PRECOMPUTED_PERSISTENT_NDVI_STATS[
    `${start}-${end}`
  ];

  if (!result) {
    return null;
  }

  const [persistentAreaHa, validNdviAreaHa, ...means] = result;

  const ndviMeans = means.map((meanNdvi, index) => ({
    year: start + index,
    meanNdvi
  }));

  return {
    success: true,
    startYear: start,
    endYear: end,
    period: `${start}–${end}`,
    persistentAreaHa,
    validNdviAreaHa,
    ndviMeans,
    interpretation:
      'Mean NDVI within locations classified as mangrove candidates in every selected year, with valid NDVI across the period. Values describe vegetation greenness, not confirmed degradation or recovery.'
  };
}

